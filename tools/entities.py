"""Generate src/entities.zig from the WHATWG named character reference table.

Usage: python3 tools/entities.py entities.json > src/entities.zig

entities.json is https://html.spec.whatwg.org/entities.json. The output is a
table sorted by name in byte order, which `entities.zig` searches one input
byte at a time while matching a named character reference.
"""

import json
import sys


def main() -> None:
    table = json.load(open(sys.argv[1], encoding="utf-8"))
    rows = sorted((name[1:], value["codepoints"]) for name, value in table.items())
    longest = max(len(name) for name, _ in rows)
    out = sys.stdout
    out.write("//! The named character references of the HTML standard, sorted by name.\n")
    out.write("//!\n")
    out.write("//! Generated by `tools/entities.py` from\n")
    out.write("//! https://html.spec.whatwg.org/entities.json. Do not edit.\n\n")
    out.write("/// One row of the table: the name without its leading `&`, and the one or\n")
    out.write("/// two code points it stands for. A second code point of zero means none.\n")
    out.write("pub const Entity = struct {\n")
    out.write("    name: []const u8,\n")
    out.write("    codepoints: [2]u21,\n")
    out.write("};\n\n")
    out.write("/// The length of the longest name, the most a match can look ahead.\n")
    out.write(f"pub const max_name_len = {longest};\n\n")
    out.write(f"/// All {len(rows)} names, sorted in byte order.\n")
    out.write("pub const table = [_]Entity{\n")
    for name, codepoints in rows:
        assert 1 <= len(codepoints) <= 2
        second = codepoints[1] if len(codepoints) == 2 else 0
        out.write(f'    .{{ .name = "{name}", .codepoints = .{{ 0x{codepoints[0]:X}, 0x{second:X} }} }},\n')
    out.write("};\n")


main()
